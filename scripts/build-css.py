#!/usr/bin/env python3
"""No-dependency CSS snapshot generator for SCSS partials written in plain CSS syntax.
For regular Sass builds, use `npx sass scss/style.scss css/style.css` after installing sass.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
parts = [
    'foundation/_base.scss', 'layout/_header.scss', 'layout/_footer.scss',
    'object/component/_buttons.scss', 'object/component/_heading.scss',
    'object/project/_hero.scss', 'object/project/_finder.scss',
    'object/project/_selection.scss', 'object/project/_about.scss',
    'object/project/_staff.scss', 'object/project/_guide.scss',
    'object/project/_store.scss', 'object/project/_instagram.scss',
    'object/project/_mobile-menu.scss', 'object/project/_reservation.scss',
    'object/project/_guide-page.scss',
    'object/utility/_display.scss',
]
contents = ['/* Generated from FLOCSS SCSS partials. Do not edit this file directly. */']
for part in parts:
    contents.append(f'\n/* {part} */\n')
    contents.append((root / 'scss' / part).read_text(encoding='utf-8'))
(root / 'css' / 'style.css').write_text('\n'.join(contents), encoding='utf-8')
print('Compiled css/style.css from', len(parts), 'SCSS partials')
